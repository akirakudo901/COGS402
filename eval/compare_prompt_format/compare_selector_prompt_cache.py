"""
Compare selector prompt styles for cache usage and cost.

Writes full ``llm_interactions`` JSON under ``eval/compare_selector_cache_runs/``
(``llm_interactions_legacy_rebuild.json``, ``llm_interactions_append_cache.json``)
and prints selector ``user_prompt`` base + prefix deltas for each run.

Run:
  python -m eval.compare_selector_prompt_cache
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict

from llm_prolog.llm_client.llm_client import LLMClient
from llm_prolog.llm_interactions_tools import (
    display_selector_user_prompt_prefix_deltas,
    save_llm_interactions_to_json,
)
from llm_prolog.pipeline import PipelineConfig, run_symbolic_hybrid_pipeline

_EVAL_DIR = Path(__file__).resolve().parent
_INTERACTIONS_DIR = _EVAL_DIR / "compare_selector_cache_runs"


@dataclass(frozen=True)
class RunSummary:
    label: str
    success: bool
    reason: str | None
    usage: Dict[str, Any]


def _to_num(v: Any) -> float:
    if isinstance(v, (int, float)):
        return float(v)
    return 0.0


def _print_summary(s: RunSummary) -> None:
    u = s.usage
    print(f"=== {s.label} ===")
    print(f"success={s.success} reason={s.reason}")
    print(f"n_requests={u.get('n_requests', 0)}")
    print(f"cost_usd={_to_num(u.get('cost_usd')):.8f}")
    print(f"prompt_tokens={int(_to_num(u.get('prompt_tokens')))}")
    print(f"completion_tokens={int(_to_num(u.get('completion_tokens')))}")
    print(f"total_tokens={int(_to_num(u.get('total_tokens')))}")
    print(f"cached_tokens={int(_to_num(u.get('cached_tokens')))}")
    print(f"cache_write_tokens={int(_to_num(u.get('cache_write_tokens')))}")
    prompt_tokens = _to_num(u.get("prompt_tokens"))
    cached_tokens = _to_num(u.get("cached_tokens"))
    cache_ratio = (cached_tokens / prompt_tokens) if prompt_tokens > 0 else 0.0
    print(f"cached/prompt={cache_ratio:.4f}")
    print()


def _print_comparison(legacy: RunSummary, append_mode: RunSummary) -> None:
    l_cost = _to_num(legacy.usage.get("cost_usd"))
    a_cost = _to_num(append_mode.usage.get("cost_usd"))
    l_cached = _to_num(legacy.usage.get("cached_tokens"))
    a_cached = _to_num(append_mode.usage.get("cached_tokens"))
    l_prompt = _to_num(legacy.usage.get("prompt_tokens"))
    a_prompt = _to_num(append_mode.usage.get("prompt_tokens"))
    cost_reduction_pct = ((l_cost - a_cost) / l_cost * 100.0) if l_cost > 0 else 0.0
    l_cached_ratio = (l_cached / l_prompt) if l_prompt > 0 else 0.0
    a_cached_ratio = (a_cached / a_prompt) if a_prompt > 0 else 0.0

    print("=== Comparison (append_cache vs legacy_rebuild) ===")
    print(f"cost_delta_usd={a_cost - l_cost:.8f}")
    print(f"cost_reduction_pct={cost_reduction_pct:.2f}%")
    print(f"cached_tokens_delta={int(a_cached - l_cached)}")
    print(f"cached_ratio_delta={a_cached_ratio - l_cached_ratio:.4f}")


def _run_once(problem: str, *, mode: str) -> RunSummary:
    client = LLMClient()
    client.reset_usage_stats()
    cfg = PipelineConfig(
        max_steps=20,
        explain=False,
        use_termination_checks=False,
        use_final_termination_check=True,
        selector_num_candidates=3,
        allow_background_premises=False,
        selector_prompt_mode=mode,
    )
    result = run_symbolic_hybrid_pipeline(
        problem=problem,
        llm=client,
        pipeline_cfg=cfg,
    )

    _INTERACTIONS_DIR.mkdir(parents=True, exist_ok=True)
    interactions_path = _INTERACTIONS_DIR / f"llm_interactions_{mode}.json"
    save_llm_interactions_to_json(result.llm_interactions, interactions_path)
    print(f"Saved LLM interactions to {interactions_path}")

    print()
    print(f"=== Selector user_prompt deltas ({mode}) ===")
    display_selector_user_prompt_prefix_deltas(result.llm_interactions)
    print()

    return RunSummary(
        label=mode,
        success=result.success,
        reason=result.reason,
        usage=client.get_usage_stats(),
    )


def main() -> None:
    problem1 = ( #autogenerated
        "A store sold 12 notebooks on Monday and 18 notebooks on Tuesday. "
        "Each notebook costs 3 dollars. How much money did the store make "
        "from notebook sales across both days?"
    )
    problem2 = ( #from gsm8k, solved easily by gpt4.1-mini
        "Nick has 60 cans. Each can takes up 30 square inches of space before "
        "being compacted and 20% of that amount after being compacted. How much "
        "space do all the cans take up after being compacted?"
    )
    problem3 = ( #from gsm8k, seems like it is difficult for gpt4.1-mini
        "A deep-sea monster rises from the waters once every hundred years to "
        "feast on a ship and sate its hunger. Over three hundred years, it has "
        "consumed 847 people. Ships have been built larger over time, so each new "
        "ship has twice as many people as the last ship. How many people were on "
        "the ship the monster ate in the first hundred years?"
    )

    legacy = _run_once(problem3, mode="legacy_rebuild")
    append_mode = _run_once(problem3, mode="append_cache")

    _print_summary(legacy)
    _print_summary(append_mode)
    _print_comparison(legacy, append_mode)


if __name__ == "__main__":
    main()

